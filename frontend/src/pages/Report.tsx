import type { ReactNode } from 'react'
import { Activity } from 'lucide-react'
import { api, useApi, type Agentic, type Finding, type Grid, type Run } from '../api'
import {
  Badge, Card, CHECK, Empty, ErrorState, Loading, ORIGIN, PageHead, READINESS_NOTE, Readiness, RunStatus, VerdictBadge,
  count, duration, href, insufficient, num, outcomeLine, quotaStopped, readinessBasis, short, when,
} from '../ui'

// The report of one run: what was tested, what broke, with what evidence, and what the run could not cover.
// Everything is read from the ledger; the suggestions at the end come from fixed rules, never from a model.

export function Report({ id }: { id: number }) {
  const run = useApi(() => api.run(id), [id])
  const grid = useApi(() => api.grid(id), [id])
  const ag = useApi(() => api.agentic(id), [id])
  const crumbs = [{ label: 'Runs', href: '#/runs' }, { label: `Run ${id}`, href: href(`runs/${id}`) }, { label: 'Report' }]
  if ((run.loading && !run.data) || (grid.loading && !grid.data) || (ag.loading && !ag.data)) {
    return <Shell id={id} crumbs={crumbs}><Card><Loading label="Loading report" /></Card></Shell>
  }
  const err = run.error ?? grid.error ?? ag.error
  if (err && !run.data) return <Shell id={id} crumbs={crumbs}><Card><ErrorState error={err} onRetry={run.reload} what="run" /></Card></Shell>
  const r = run.data as Run
  const g = grid.data ?? { flows: [], attacks: [], cells: [] }
  const a = ag.data ?? { findings: [], steps: [], app_map: null, strategy: null }
  return (
    <>
      <PageHead
        crumbs={crumbs}
        title={`Report · Run ${r.id}`}
        purpose="What this run tested, what broke and on what evidence, and what it could not cover. Read from the recorded run; nothing here is generated by a model."
        meta={
          <>
            <RunStatus run={r} />
            <span className="mono">{short(r.commit_sha)}</span>
            <span>{r.branch ?? 'local'}</span>
            <span>{when(r.started_at)}</span>
            {r.duration_s != null && <span>{duration(r.duration_s)}</span>}
          </>
        }
        action={<a className="btn" href={href(`runs/${r.id}`)}><Activity size={15} aria-hidden="true" /> Run activity</a>}
      />
      <div className="page-body report">
        {(grid.error || ag.error) && <Card><ErrorState error={(grid.error ?? ag.error)!} onRetry={() => { grid.reload(); ag.reload() }} /></Card>}
        <Summary run={r} findings={a.findings} grid={g} />
        <Broke run={r} grid={g} findings={a.findings} />
        <Tested run={r} grid={g} agentic={a} />
        <Limits run={r} grid={g} findings={a.findings} />
        <Suggestions run={r} grid={g} findings={a.findings} />
      </div>
    </>
  )
}

function Shell({ id, crumbs, children }: { id: number; crumbs: { label: string; href?: string }[]; children: ReactNode }) {
  return (
    <>
      <PageHead crumbs={crumbs} title={`Report · Run ${id}`} />
      <div className="page-body">{children}</div>
    </>
  )
}

const confirmedOf = (fs: Finding[]) => fs.filter((f) => f.verdict === 'fail' || f.verdict === 'flaky')
const failingCells = (g: Grid) => g.cells.filter((c) => c.score_verdict === 'fail' || c.score_verdict === 'flaky')
const cellsOf = (g: Grid, verdict: string) => g.cells.filter((c) => c.score_verdict === verdict).length
/** "7 failed, 1 flaky": the same split as report.md, so a flaky check is never counted as a failed one. */
const failingHint = (g: Grid) =>
  [cellsOf(g, 'fail') ? `${cellsOf(g, 'fail')} failed` : '', cellsOf(g, 'flaky') ? `${cellsOf(g, 'flaky')} flaky` : ''].filter(Boolean).join(', ')

function Summary({ run, findings, grid }: { run: Run; findings: Finding[]; grid: Grid }) {
  const b = run.breakdown
  const confirmed = confirmedOf(findings).length
  const stop = quotaStopped(run)
  const line = outcomeLine(run, confirmed, cellsOf(grid, 'fail'), cellsOf(grid, 'flaky'))
  return (
    <Card title="Summary" hint="observed">
      <div className="stack">
        <p className="outcome-line">{line}</p>
        <div className="facts">
          <div className="fact">
            <span className="label">Readiness</span>
            <span className="value"><Readiness breakdown={b} /></span>
            <span className="note">{readinessBasis(b)}</span>
          </div>
          <div className="fact">
            <span className="label">Completion</span>
            <span className="value">{stop ? 'Stopped early' : run.status === 'finished' ? 'Ran to the end' : run.status === 'running' ? 'In progress' : 'Aborted'}</span>
            <span className="note">{stop ?? (run.coverage?.completion?.model_stop || 'no limit stopped the run')}</span>
          </div>
          <div className="fact">
            <span className="label">Replays</span>
            <span className="value">{run.coverage?.replay_state === 'none' ? 'On live state' : 'From a restarted app'}</span>
            <span className="note">{run.coverage?.replay_state === 'none' ? 'URL mode: the app was not reset between replays' : 'each replay attempt starts clean'}</span>
          </div>
        </div>
        {b?.formula && !insufficient(b) && <p className="formula">{b.formula}</p>}
        <p className="footnote">{READINESS_NOTE}</p>
      </div>
    </Card>
  )
}

function Broke({ run, grid, findings }: { run: Run; grid: Grid; findings: Finding[] }) {
  const confirmed = confirmedOf(findings)
  const notReproduced = findings.filter((f) => f.verdict === 'unconfirmed')
  const failing = failingCells(grid)
  const regressed = run.breakdown?.regressed ?? 0
  return (
    <section className="report-section" aria-labelledby="broke">
      <h2 id="broke">What broke <span className="label-tag">observed</span></h2>
      <p className="lede">Each finding was replayed from its first step and judged by plain code; its page holds the evidence of every attempt.</p>
      <Card title="Findings confirmed by replay" hint={count(confirmed.length, 'finding')} flush>
        {!confirmed.length ? (
          <Empty title="None confirmed">{findings.length ? 'Candidates were flagged but none reproduced in replay (see below).' : 'Exploration flagged nothing to replay.'} That is not evidence the app is safe; see what was tested and the coverage limits.</Empty>
        ) : (
          <FindingTable findings={confirmed} />
        )}
      </Card>
      {(failing.length > 0 || grid.cells.length > 0) && (
        <Card title="Baseline checks that failed or were flaky" hint={grid.cells.length ? `${failingHint(grid) || 'none'} of ${count(grid.cells.length, 'check')}` : undefined} flush>
          {!failing.length ? (
            <Empty title="No baseline check failed or was flaky">Every applicable fixed attack passed (see what was tested below).</Empty>
          ) : (
            <div className="table-wrap">
              <table>
                <thead><tr><th>Flow</th><th>Attack</th><th>Result</th><th>What fired</th><th>Bugs</th></tr></thead>
                <tbody>
                  {failing.map((c) => {
                    const [tone, label] = CHECK[c.score_verdict] ?? ['', c.score_verdict]
                    return (
                      <tr key={c.check_id}>
                        <td className="mono">{c.flow_id}</td>
                        <td className="mono">{c.attack_id}</td>
                        <td><Badge tone={tone}>{label}</Badge>{c.reused && <span className="sub">reused from an earlier run</span>}</td>
                        <td className="mono xs">{c.oracle_hits || '–'}</td>
                        <td>{c.bug_ids.length ? c.bug_ids.map((b, i) => <span key={b}>{i > 0 && ', '}<a href={href(`bugs/${b}`)}>{b}</a></span>) : '–'}</td>
                      </tr>
                    )
                  })}
                </tbody>
              </table>
            </div>
          )}
        </Card>
      )}
      {regressed > 0 && <p className="muted small">{count(regressed, 'bug')} marked fixed earlier came back in this run (regressions).</p>}
      {notReproduced.length > 0 && (
        <Card title="Flagged but not reproduced" hint="not a pass: replay did not show the break again" flush>
          <FindingTable findings={notReproduced} />
        </Card>
      )}
    </section>
  )
}

function FindingTable({ findings }: { findings: Finding[] }) {
  return (
    <div className="table-wrap">
      <table>
        <thead><tr><th>Finding</th><th>Result</th><th>What fired</th><th>Found by</th></tr></thead>
        <tbody>
          {findings.map((f) => (
            <tr key={f.id}>
              <td><a href={href(`findings/${f.id}`)}>{f.title || 'Untitled finding'}</a>{f.key && <span className="sub mono">{f.key}</span>}</td>
              <td><VerdictBadge verdict={f.verdict} /></td>
              <td className="mono xs">{f.oracle_ids || '–'}</td>
              <td className="small">{ORIGIN[f.origin ?? ''] ?? f.origin ?? '–'}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  )
}

function Tested({ run, grid, agentic }: { run: Run; grid: Grid; agentic: Agentic }) {
  const cov = run.coverage
  const ag = cov?.agentic
  const hypotheses = agentic.strategy?.strategy?.hypotheses ?? []
  const phases = cov?.completion?.phases ?? {}
  return (
    <section className="report-section" aria-labelledby="tested">
      <h2 id="tested">What was tested <span className="label-tag">observed</span></h2>
      <div className="grid-2">
        <Card title="Exploration" hint={ag ? 'model-driven, black box' : undefined}>
          {ag ? (
            <dl className="kv">
              <dt>Recon</dt><dd>{num(ag.pages)} pages, {num(ag.endpoints)} endpoints</dd>
              <dt>Started as</dt><dd>{ag.start_as ? `test account ${ag.start_as}, logged in by setup and verified (a test precondition, not the agent logging in)` : 'logged out'}</dd>
              <dt>Steps</dt><dd>{num(ag.steps)}{ag.ai_steps != null ? ` (${num(ag.ai_steps)} chosen by the model, ${num(ag.code_probe_steps)} Sentri probes, ${num(ag.fallback_steps)} fallbacks)` : ''}</dd>
              {ag.distinct_states != null && <><dt>Distinct states</dt><dd>{num(ag.distinct_states)}{ag.states_by_identity ? ` (${Object.entries(ag.states_by_identity).map(([k, v]) => `${k} ${v}`).join(', ')})` : ''}</dd></>}
              <dt>Candidates</dt><dd>{num(ag.candidates)} replayed: {num(ag.confirmed)} confirmed, {num(ag.unconfirmed)} not reproduced, {num(ag.inconclusive)} inconclusive</dd>
              <dt>Ended</dt><dd>{ag.exploration_stop || '–'}</dd>
            </dl>
          ) : (
            <Empty title="Not run">{phases.agentic ?? 'This run had no agentic phase.'}</Empty>
          )}
        </Card>
        <Card title="Attack ideas the model planned" hint={hypotheses.length ? count(hypotheses.length, 'hypothesis', 'hypotheses') : undefined}>
          {hypotheses.length ? (
            <ul className="bullets small">
              {hypotheses.map((h) => <li key={h.id}>{h.title}</li>)}
            </ul>
          ) : (
            <Empty title="No strategy recorded">Strategies are recorded when a model plans the run.</Empty>
          )}
        </Card>
      </div>
      <Card title="Baseline suite" hint="each attacked flow × six fixed attacks, 3 attempts" flush>
        {!grid.cells.length ? (
          <Empty title="Not run">{phases.baseline ? `${phases.baseline[0].toUpperCase()}${phases.baseline.slice(1)}.` : 'The contract has no attacked flows, or the run used agentic mode only.'} Without it there is no readiness score.</Empty>
        ) : (
          <div className="table-wrap">
            <table className="matrix">
              <thead><tr><th>Flow</th>{grid.attacks.map((x) => <th key={x} className="mono">{x}</th>)}</tr></thead>
              <tbody>
                {grid.flows.map((f) => (
                  <tr key={f}>
                    <td className="mono">{f}</td>
                    {grid.attacks.map((x) => {
                      const c = grid.cells.find((y) => y.flow_id === f && y.attack_id === x)
                      if (!c) return <td key={x} className="faint">–</td>
                      const [tone, label, icon] = CHECK[c.score_verdict] ?? ['', c.score_verdict]
                      return <td key={x}><Badge tone={tone} icon={icon} title={c.oracle_hits || undefined}>{label}</Badge></td>
                    })}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Card>
    </section>
  )
}

/** What the run could not cover. Plain statements from the record; together they bound what the summary means. */
function limitsOf(run: Run, grid: Grid, findings: Finding[]): string[] {
  const out: string[] = []
  const cov = run.coverage
  const ag = cov?.agentic
  const b = run.breakdown
  const stop = quotaStopped(run)
  if (run.status === 'aborted') out.push('The run was aborted; later phases did not run.')
  if (run.status === 'running') out.push('The run is still in progress.')
  if (insufficient(b)) out.push('No applicable baseline check ran, so the run has no readiness score.')
  if (stop) out.push(`Model use stopped early (${stop}); exploration ended before its own limit.`)
  for (const [phase, state] of Object.entries(cov?.completion?.phases ?? {})) {
    if (!/^done/.test(state)) out.push(`${phase[0].toUpperCase()}${phase.slice(1)}: ${state}.`)
  }
  if (cov?.replay_state === 'none') out.push('Replays ran on the live app without a reset, so the three attempts are not independent.')
  const na = grid.cells.filter((c) => c.score_verdict === 'na').length
  if (na) out.push(`${count(na, 'baseline check')} did not apply to this app's flows (N/A).`)
  const inconclusive = grid.cells.filter((c) => c.score_verdict === 'error').length + (ag?.inconclusive ?? 0)
  if (inconclusive) out.push(`${count(inconclusive, 'check')} ended inconclusive (they neither confirm nor clear anything).`)
  if (ag?.untried_options_left) out.push(`${count(ag.untried_options_left, 'option')} the explorer saw were never tried.`)
  if (findings.some((f) => f.verdict === 'unconfirmed')) out.push('Some candidates did not reproduce in replay; that is not evidence the behaviour is correct.')
  if (cov?.caveat) out.push(cov.caveat)
  return out
}

function Limits({ run, grid, findings }: { run: Run; grid: Grid; findings: Finding[] }) {
  const items = limitsOf(run, grid, findings)
  return (
    <section className="report-section" aria-labelledby="limits">
      <h2 id="limits">Coverage limits <span className="label-tag">observed</span></h2>
      <Card>
        {items.length ? <ul className="bullets">{items.map((t) => <li key={t}>{t}</li>)}</ul> : <p className="muted">No limits recorded beyond the scope of the contract itself.</p>}
      </Card>
    </section>
  )
}

/** Next steps from fixed rules over the recorded data. Suggestions, not findings, and never a model's opinion. */
function suggestionsFor(run: Run, grid: Grid, findings: Finding[]): { text: ReactNode; why: string }[] {
  const out: { text: ReactNode; why: string }[] = []
  const cov = run.coverage
  const ag = cov?.agentic
  const confirmed = confirmedOf(findings)
  const failing = failingCells(grid)
  if (confirmed.length || failing.length) {
    out.push({ text: <>Fix what broke, then run again: Sentri re-checks every confirmed finding and open bug on later runs. Open bugs are in <a href={href('findings', { view: 'bugs', status: 'open' })}>Bugs across runs</a>.</>, why: `${count(confirmed.length, 'confirmed finding')}, ${count(cellsOf(grid, 'fail'), 'failed baseline check')} and ${cellsOf(grid, 'flaky')} flaky in this run` })
    out.push({ text: <>If a break is the app working as designed, mark its bug intended on the bug's page, with a reason.</>, why: 'only a person can mark a bug intended' })
  }
  if (!grid.cells.length) out.push({ text: <>Add attacked flows to the contract so the six fixed attacks can run and the run gets a comparable readiness score.</>, why: 'no baseline check ran' })
  if (!ag) out.push({ text: <>Choose a model in <a href="#/new">New run</a> to add recon and exploration; without one only the fixed attacks run.</>, why: cov?.completion?.phases?.agentic ?? 'no agentic phase' })
  const stop = quotaStopped(run)
  if (stop) out.push({ text: <>Run again when the model's quota resets, or with a higher token or budget limit, so exploration can reach its own end.</>, why: stop })
  if (cov?.replay_state === 'none') out.push({ text: <>Let Sentri start the app (command or Docker mode) so each replay begins from a clean state.</>, why: 'replays ran on live state (URL mode)' })
  if (findings.some((f) => f.verdict === 'unconfirmed')) out.push({ text: <>Look at the candidates that did not reproduce: timing-dependent breaks can hide behind a passing replay.</>, why: 'flagged but not reproduced' })
  if (ag?.untried_options_left && ag.untried_options_left > 0) out.push({ text: <>A longer run could try the options exploration saw but never used.</>, why: `${num(ag.untried_options_left)} untried options` })
  if (!out.length) out.push({ text: <>Widen coverage: add more flows and roles to the contract; a clean run only speaks for what it tested.</>, why: 'nothing failed in what was tested' })
  return out
}

function Suggestions({ run, grid, findings }: { run: Run; grid: Grid; findings: Finding[] }) {
  const items = suggestionsFor(run, grid, findings)
  return (
    <section className="report-section" aria-labelledby="next">
      <h2 id="next">Suggested next steps <span className="label-tag">suggestions, from fixed rules over the record</span></h2>
      <Card className="quiet">
        <ul className="bullets suggestions">
          {items.map((s, i) => <li key={i}>{s.text}<span className="why">because: {s.why}</span></li>)}
        </ul>
      </Card>
    </section>
  )
}
